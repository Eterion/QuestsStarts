-- Run from the pinned QuestieDB checkout. Compare independent expansion views,
-- not merely an export with the same source that produced it.
local root,mode=assert(arg[1]),assert(arg[2])
assert(mode=='source' or mode=='audit','Expected source or audit mode')
local client=dofile('emulator/client.lua')
client.install({expansion=mode=='source' and 'Classic' or 'Forever',season=mode=='source' and 'SoD' or nil,
    faction='Horde',raceName='Undead',raceFile='Scourge',raceId=5,classFile='WARRIOR',classId=1})
local db=dofile('emulator/metadata.lua').loadAddon('QuestieDB.toc','QuestieDB')
local snapshot=root..'/work/inherited-class-source.lua'
if mode=='source' then
    local rows={}
    for _,id in ipairs(db.Quest.GetAllIds()) do
        local mask=db.Quest.requiredClasses(id)
        if mask and mask~=0 then
            rows[id]={name=db.Quest.name(id),requiredClasses=mask,parentQuest=db.Quest.parentQuest(id)}
        end
    end
    local serialize=dofile(root..'/tools/serialize.lua')
    local file=assert(io.open(snapshot,'wb'))
    file:write('return '..serialize(rows)) file:close()
    return
end
local original=dofile(snapshot)
local ns={}
assert(loadfile(root..'/addon/QuestsStarts/Data/Tirisfal.lua'))('QuestsStarts',ns)
local reviews=dofile(root..'/tools/class-gate-reviews.lua')
local decisions,reviewed={},0
for key,review in pairs(reviews) do
    for _,id in ipairs(review.ids) do
        assert(not decisions[id],'Duplicate class review: '..id)
        local q=assert(ns.Data.quests[id],'Reviewed quest missing: '..id)
        local source=assert(original[id],'Reviewed original class restriction missing: '..id)
        assert(source.name==q.name and source.requiredClasses==review.originalMask,'Original class evidence changed: '..id)
        assert((db.Quest.requiredClasses(id) or 0)==0,'Forever source class mask changed; re-review required: '..id)
        for field,value in pairs(review.fields) do assert(q[field]==value,'Reviewed eligibility field regressed: '..id..'/'..field) end
        decisions[id]=review.disposition
        reviewed=reviewed+1
    end
end
assert(reviewed==49,'Expected a disposition for each of the 49 reviewed differences')
local differences,compared={},0
for id,q in pairs(ns.Data.quests) do
    local source=original[id]
    -- Matching IDs alone are insufficient: expansions sometimes reuse them.
    if source and source.name==q.name then
        compared=compared+1
        if source.requiredClasses~=(q.requiredClasses or 0) then
            assert(decisions[id],'Unreviewed inherited class difference: '..id..' '..q.name)
            differences[#differences+1]=id
        end
    end
end
table.sort(differences)
local file=assert(io.open(root..'/docs/inherited-class-audit.md','wb'))
file:write('# Inherited class metadata comparison\n\n')
file:write('Generated by `tools/audit-inherited-classes.lua` from pinned QuestieDB revision `'..ns.Data.revision..'`.\n\n')
file:write(compared..' bundled quests match class-restricted original Era/SoD records by ID and name. All '..reviewed..' class-mask differences have explicit dispositions; zero are unreviewed.\n\n')
file:write('42 library quests and Anyone Can Cook retain shared access. All three Earthmother steps are corrected to Tauren-only, with no class gate. The three Dragonslayer entries are quarantined: their actual Forever availability remains unverified, so default map markers are suppressed; opt-in unverified markers remain visibly uncertain. This is not a claim of confirmed Dragonslayer class eligibility. Evidence and confidence are recorded in [the decision notes](class-gate-decisions.md).\n\n')
file:write('This comparison catches missing restrictions outside class quest categories, including sparse imported records. It complements the nine-profile source/export and runtime-filter audits.\n\n')
file:write('| ID | Quest | Original mask | Forever mask | Disposition |\n| --- | --- | --- | --- | --- |\n')
for _,id in ipairs(differences) do
    local q=ns.Data.quests[id]
    file:write(string.format('| %d | %s | %d | %d | %s |\n',id,q.name,original[id].requiredClasses,q.requiredClasses or 0,decisions[id]))
end
local lockpicks=ns.Data.quests[78270]
assert(lockpicks.requiredClasses==original[78270].requiredClasses,'Goblin Lockpicks lost its source class gate')
assert(lockpicks.parentQuest==original[78270].parentQuest,'Goblin Lockpicks lost its source parent gate')
file:write('\nGoblin Lockpicks (78270) matches the original rogue mask and active-parent gate through a documented local override. New unreviewed differences or regressions in any reviewed field fail the build.\n')
file:close()
print(string.format('Inherited class audit: %d comparable quests; %d reviewed dispositions; zero unreviewed differences; Goblin Lockpicks class/parent regression verified.',compared,reviewed))
